#!/usr/bin/env python3
"""Generates backend/migrations/005_real_photos.sql — wires the photos from scripts/build_photos.py into the site.
Only placeholder slots (placehold.co / empty) are filled; anything you uploaded in the admin is left alone. Re-runnable."""
import os
q = lambda s: s.replace("\\", "\\\\").replace("'", "''")
A = "/assets/photos/"
PLACEHOLDER = "image_url LIKE 'https://placehold.co/%'"
out = ["-- Generated by scripts/gen_photo_content.py. Safe to re-run; never overwrites admin uploads.",
       "-- Usage: mysql -u root -p < backend/migrations/005_real_photos.sql", "USE avm_website;", ""]

# ---- hero slides (added after any existing slides)
out.append("-- Hero slides")
for img, title, sub in [("hero-campus", "A Campus Built for Learning", "Adarsh Vidya Mandir, Muzaffarpur"),
                        ("hero-culture", "Celebrating Our Culture", "Music, dance and tradition"),
                        ("hero-annualday", "Teamwork. Confidence. Leadership.", "Annual Day 2024")]:
    out.append(f"INSERT INTO page_items (page_slug, title, subtitle, description, image_url, file_url, sort_order) "
               f"SELECT 'home-hero','{q(title)}','{q(sub)}','','{A}{img}.jpg','',COALESCE((SELECT MAX(sort_order) FROM page_items WHERE page_slug='home-hero'),0)+1 "
               f"FROM DUAL WHERE EXISTS (SELECT 1 FROM pages WHERE slug='home-hero') AND NOT EXISTS (SELECT 1 FROM page_items WHERE page_slug='home-hero' AND image_url='{A}{img}.jpg');")

# ---- gallery
out += ["", "-- Gallery: drop the sample placeholders, add real photos after whatever is already there",
        "DELETE FROM gallery WHERE image_url LIKE 'https://placehold.co/%';", "SET @n := (SELECT COALESCE(MAX(sort_order),0) FROM gallery);"]
G = [("gal-republic-day","Republic Day celebrations"),("gal-human-pyramid","Annual Day 2024"),("gal-steps-group","Celebration on the steps"),
     ("gal-costume-day","Costume day"),("gal-rangoli","Flower rangoli"),("gal-chess","Chess competition"),("gal-classroom","In the classroom"),
     ("gal-early-years","Early years classroom"),("gal-dandiya-teachers","Dandiya celebration"),("gal-dandiya-kids","Dandiya with the little ones"),
     ("gal-pineapple","Fancy dress"),("gal-dance-portrait","Cultural programme"),("gal-dance-group","Tricolour dance"),
     ("gal-annualday-pink","Annual Day performance"),("gal-annualday-orange","Annual Day performance"),("gal-annualday-stage","Annual Day 2024"),
     ("gal-inauguration","Inauguration of the new building"),("gal-teachers","Our teachers"),("gal-christmas","Christmas celebration"),
     ("gal-staff-students","Teachers and students together"),("gal-campus","Our campus"),("gal-garba-ground","Garba on the ground"),
     ("gal-rangoli-portrait","Rangoli in the classroom"),("gal-craft-kids","Craft time"),("gal-bhumi-pujan","Bhumi Pujan — where it began")]
for name, cap in G:
    out.append(f"INSERT INTO gallery (image_url, caption, sort_order, is_active) SELECT '{A}{name}.jpg','{q(cap)}',(@n := @n + 1),1 "
               f"FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM gallery WHERE image_url='{A}{name}.jpg');")

# ---- page banners (parent + all its sub-pages), only where still a placeholder
out += ["", "-- Page banners"]
B = {"about-us": "banner-about", "academics": "banner-academics", "governing-body": "banner-governing", "sports-and-activities": "banner-sports",
     "downloads": "banner-downloads", "pastoral": "banner-pastoral", "public-disclosure": "banner-disclosure", "contact-us": "banner-contact",
     "alumni": "banner-alumni", "admission": "banner-admission"}
for slug, img in B.items():
    out.append(f"UPDATE pages SET banner_url='{A}{img}.jpg' WHERE (slug='{slug}' OR slug LIKE '{slug}/%') AND banner_url LIKE 'https://placehold.co/%';")
out.append(f"UPDATE pages SET banner_url='{A}banner-academics.jpg' WHERE slug='academics/facilities' AND banner_url LIKE 'https://placehold.co/%';")
out.append(f"UPDATE pages SET banner_url='{A}why-bg.jpg' WHERE slug='home-why' AND banner_url='';")
out += ["", "-- Image beside the text",
        f"UPDATE pages SET image_url='{A}about-avm.jpg' WHERE slug='about-us/about-avm' AND image_url='';",
        f"UPDATE pages SET image_url='{A}pastoral-overview.jpg' WHERE slug='pastoral/overview' AND image_url='';"]

# ---- card photos, matched by page + title, only where still a placeholder
out += ["", "-- Card photos"]
C = [("academics/curriculum","Pre-Primary","cur-preprimary"),("academics/curriculum","Primary","cur-primary"),("academics/curriculum","Middle School","cur-middle"),
     ("academics/curriculum","Secondary","cur-secondary"),("academics/curriculum","Senior Secondary","cur-senior"),
     ("academics/approach-to-learning","Experiential Learning","learn-experiential"),("academics/approach-to-learning","Critical Thinking","learn-thinking"),
     ("academics/approach-to-learning","Technology in the Classroom","learn-tech"),("academics/approach-to-learning","Continuous Assessment","learn-assessment"),
     ("sports-and-activities/student-leadership","Student Council","lead-council"),("sports-and-activities/student-leadership","House Captains","lead-houses"),
     ("sports-and-activities/student-leadership","Club Leaders","lead-clubs"),
     ("sports-and-activities/activities","Music & Dance","act-dance"),("sports-and-activities/activities","Art & Craft","act-craft"),
     ("sports-and-activities","Music & Dance","act-dance")]
for slug, title, img in C:
    out.append(f"UPDATE page_items SET image_url='{A}{img}.jpg' WHERE page_slug='{slug}' AND title='{q(title)}' AND {PLACEHOLDER};")
out.append("")
out.append("-- New activity cards with real photos")
for title, sub, desc, img in [("Chess", "Indoor games", "Regular practice and inter-school chess competitions.", "act-chess"),
                              ("Annual Day", "Stage", "Dance, drama and music in front of the whole school community.", "act-annualday"),
                              ("Festival Celebrations", "Culture", "Costume days, dandiya, rangoli and festivals celebrated together.", "act-festival"),
                              ("Republic Day", "National pride", "Tricolour performances and a flag hoisting that students look forward to.", "act-republic")]:
    out.append(f"INSERT INTO page_items (page_slug, title, subtitle, description, image_url, file_url, sort_order) "
               f"SELECT 'sports-and-activities/activities','{q(title)}','{q(sub)}','{q(desc)}','{A}{img}.jpg','',"
               f"COALESCE((SELECT MAX(sort_order) FROM page_items WHERE page_slug='sports-and-activities/activities'),0)+1 FROM DUAL "
               f"WHERE EXISTS (SELECT 1 FROM pages WHERE slug='sports-and-activities/activities') "
               f"AND NOT EXISTS (SELECT 1 FROM page_items WHERE page_slug='sports-and-activities/activities' AND title='{q(title)}');")

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
open(os.path.join(root, "backend/migrations/005_real_photos.sql"), "w").write("\n".join(out) + "\n")
print("wrote 005_real_photos.sql")
